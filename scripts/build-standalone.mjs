import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const distDirectory = resolve(projectRoot, "dist")
const standalonePath = resolve(projectRoot, "camaroes-inc.html")
let html = await readFile(resolve(distDirectory, "index.html"), "utf8")

const stylesheetTags = [...html.matchAll(/<link\b(?=[^>]*\brel="stylesheet")(?=[^>]*\bhref="([^"]+)")[^>]*>/g)]
const moduleTags = [...html.matchAll(/<script\b(?=[^>]*\btype="module")(?=[^>]*\bsrc="([^"]+)")[^>]*>\s*<\/script>/g)]

if (stylesheetTags.length === 0 || moduleTags.length === 0) {
  throw new Error("Expected stylesheet and module bundles in dist/index.html")
}

for (const [tag, assetPath] of stylesheetTags) {
  if (/^https?:\/\//i.test(assetPath)) continue
  const css = await readFile(resolve(distDirectory, assetPath), "utf8")
  html = html.replace(tag, () => `<style>${css}</style>`)
}

for (const [tag, assetPath] of moduleTags) {
  const javascript = await readFile(resolve(distDirectory, assetPath), "utf8")
  const safeJavascript = javascript.replace(/<\/script/gi, "<\\/script")
  html = html.replace(tag, () => `<script type="module">${safeJavascript}</script>`)
}

html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by npm run build:standalone; do not edit by hand. -->")
await writeFile(standalonePath, html, "utf8")
console.log(`Updated ${standalonePath}`)